"""Turns the filled page of the Falafel paper (HTML with TeX formulas) into a LaTeX document.

build.py calls convert() with the same filled template that it writes as falafel-paper.html,
except that each figure is a <tikz name="..."> element in place of the inline SVG. So the page
and the PDF have the same text, the same formulas and the same tables.

The converter knows only the elements the template uses, and stops on anything else. The text of
the paper refers to sections, theorems, figures, tables and the one numbered formula by number, so
the converter checks that the numbers written in the template are the numbers LaTeX will give.
"""
import re, textwrap
from html.parser import HTMLParser

PREAMBLE = r"""% Generated by build.py from paper.template.html and the formulas in build.py.
% Do not edit this file. Edit the template or build.py and run build.py again.
% Compile with XeLaTeX or LuaLaTeX (the file uses fontspec), for example: tectonic falafel-paper.tex
\documentclass[11pt,a4paper]{amsart}
\usepackage[text={5.9in,8.9in},centering]{geometry}
\raggedbottom  % a page that ends early stays short; its gaps are not stretched to fill it
\usepackage{fontspec}
\newfontfamily\leanfont[NFSSFamily=leanmono]{DejaVuSansMono.ttf}
\usepackage{amssymb}
\usepackage{array,booktabs,float}
\usepackage{fancyvrb}
\usepackage{tikz}
\definecolor{accent}{HTML}{1D4C9A}
\definecolor{tintA}{HTML}{DBE5F6}
\definecolor{tintB}{HTML}{F4E4C6}
\definecolor{tintO}{HTML}{E6E6EA}
\definecolor{hair}{HTML}{A9ABB5}
\definecolor{old}{HTML}{B4B6C0}
\usepackage[colorlinks,allcolors=accent]{hyperref}

\newtheorem{theorem}{Theorem}
\newtheorem{lemma}{Lemma}
\newtheorem{corollary}[lemma]{Corollary}
\theoremstyle{definition}
\newtheorem{definition}{Definition}
\newtheorem*{example}{Example}
\theoremstyle{remark}
\newtheorem{remark}{Remark}

% A list whose items carry their own labels, such as (a) or (W1). The argument is the widest label.
\newenvironment{marked}[1]{%
  \begin{list}{}{\settowidth{\labelwidth}{\textup{#1}}%
    \setlength{\leftmargin}{\labelwidth}\addtolength{\leftmargin}{\labelsep}%
    \addtolength{\leftmargin}{1.3em}%
    \setlength{\itemsep}{1pt}\setlength{\parsep}{0pt}\setlength{\topsep}{3pt}%
    \setlength{\partopsep}{0pt}\renewcommand{\makelabel}[1]{\textup{##1}\hfil}}}%
  {\end{list}}

% Put at the start of a statement (theorem, lemma, corollary, definition, example): no page break
% inside it. \@endparpenalty is left alone, so that a page can still end right after the statement.
\makeatletter
\newcommand{\unbroken}{\interlinepenalty\@M \@beginparpenalty\@M \@itempenalty\@M
  \predisplaypenalty\@M \postdisplaypenalty\@M}
\makeatother

\title{@@TITLE@@}
\author{@@AUTHOR@@}
\date{@@DATE@@}

\begin{document}

\begin{abstract}
@@ABSTRACT@@
\end{abstract}

\maketitle

@@BODY@@

\end{document}
"""

MATH = re.compile(r"(\\\(.*?\\\)|\\\[.*?\\\])", re.S)
SPECIAL = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$",
           "\xa0": "~", "\u2019": "'", "\u201c": "``", "\u201d": "''", "\u2013": "--"}
WIDTH = 100


class Node:
    def __init__(self, tag, attrs):
        self.tag, self.attrs, self.kids = tag, dict(attrs), []

    def has(self, c):
        return c in (self.attrs.get("class") or "").split()

    def nodes(self):
        return [k for k in self.kids if isinstance(k, Node)]

    def find(self, tag):
        """All descendants with this tag, in document order."""
        out = []
        for k in self.nodes():
            if k.tag == tag: out.append(k)
            out += k.find(tag)
        return out

    def text(self):
        return "".join(k if isinstance(k, str) else k.text() for k in self.kids)


class _Tree(HTMLParser):
    VOID = {"meta", "link", "br"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("root", []); self.stack = [self.root]

    def handle_starttag(self, tag, attrs):
        n = Node(tag, attrs); self.stack[-1].kids.append(n)
        if tag not in self.VOID: self.stack.append(n)

    def handle_endtag(self, tag):
        assert self.stack[-1].tag == tag, (tag, self.stack[-1].tag)
        self.stack.pop()

    def handle_data(self, data):
        k = self.stack[-1].kids
        if k and isinstance(k[-1], str): k[-1] += data
        else: k.append(data)


def tex_text(s, cite):
    """Plain text of the page as LaTeX. Formulas are kept as they are."""
    out = []
    for i, part in enumerate(MATH.split(s)):
        if i % 2:
            assert part.startswith(r"\("), "display formula inside a paragraph: " + part
            out.append(re.sub(r"\s+", " ", part))
        else:
            assert "\\" not in part and "{" not in part and "}" not in part, part
            part = "".join(SPECIAL.get(c, c) for c in re.sub(r"[ \t\r\n]+", " ", part))
            assert all(ord(c) < 256 for c in part), part
            if cite: part = re.sub(r"\[(\d+)\]", r"\\cite{ref\1}", part)
            out.append(part)
    return "".join(out)


def wrap(s):
    return textwrap.fill(s.strip(), WIDTH, break_long_words=False, break_on_hyphens=False)


class Conv:
    def __init__(self, figures, listing_pt):
        self.figures, self.listing_pt = figures, listing_pt
        self.n = dict.fromkeys(["section", "appendix", "theorem", "lemma", "definition", "remark",
                                "figure", "table", "equation"], 0)
        self.in_proof = False; self.cite = True; self.meta = {}

    def count(self, counter, written):
        self.n[counter] += 1
        assert self.n[counter] == int(written), "%s %s is number %d in LaTeX" % (counter, written, self.n[counter])

    # ---- inline content ----------------------------------------------------------------------
    def inline(self, kids):
        out = []
        for k in kids:
            if isinstance(k, str): out.append(tex_text(k, self.cite))
            elif k.tag == "i": out.append(r"\emph{%s}" % self.inline(k.kids))
            elif k.tag == "code": out.append(r"\texttt{%s}" % tex_text(k.text(), False))
            elif k.tag == "a" and not self.cite:               # in the references: on its own line
                out[-1] = out[-1].rstrip(); out.append(r"\newline\url{%s}" % k.attrs["href"])
            elif k.tag == "a": out.append(r"\url{%s}" % k.attrs["href"])
            elif k.tag == "span" and k.has("qed"): out.append("" if self.in_proof else r"\qed")
            else: raise ValueError("inline <%s class=%r>" % (k.tag, k.attrs.get("class")))
        return "".join(out)

    def par(self, kids):
        return wrap(self.inline(kids))

    @staticmethod
    def split(node, *classes):
        """The spans of the given classes among the children, and the other children."""
        marks = [k for k in node.nodes() if k.tag == "span" and any(k.has(c) for c in classes)]
        return marks, [k for k in node.kids if not any(k is m for m in marks)]

    # ---- block content -----------------------------------------------------------------------
    def blocks(self, kids):
        """A list of (kind, text). The kind is par, parni (not indented), display or env."""
        out = []
        for k in kids:
            if isinstance(k, str):
                for i, part in enumerate(MATH.split(k)):
                    if i % 2:
                        assert part.startswith(r"\["), part
                        assert "\n\n" not in part, part
                        out.append(("display", part.strip()))
                    else:
                        assert not part.strip(), "text outside a paragraph: %r" % part
            else:
                out += self.block(k)
        return out

    def join(self, bl):
        out = ""
        for i, (kind, s) in enumerate(bl):
            prev = bl[i - 1][0] if i else None
            if prev is None: out = (r"\noindent" + "\n" if kind == "parni" else "") + s
            elif kind == "display" and prev in ("par", "parni"): out += "\n" + s
            elif kind == "parni" and prev == "display": out += "\n" + s
            elif kind == "parni": out += "\n\n" + r"\noindent" + "\n" + s
            else: out += "\n\n" + s
        return out

    def block(self, k):
        t = k.tag
        if t == "h1": self.meta["title"] = self.inline(k.kids).strip(); return []
        if t == "p" and k.has("author"): self.meta["author"] = self.inline(k.kids).strip(); return []
        if t == "p" and k.has("date"): self.meta["date"] = self.inline(k.kids).strip(); return []
        if t == "div" and k.has("abstract"):
            p, = k.nodes()
            assert p.nodes()[0].tag == "b" and p.nodes()[0].text() == "Abstract."
            self.meta["abstract"] = self.par([x for x in p.kids if x is not p.nodes()[0]]); return []
        if t == "h2": return self.heading(k)
        if t == "p": return [("parni" if k.has("noindent") else "par", self.par(k.kids))]
        if t == "div" and k.has("eq"): return self.equation(k)
        if t == "div" and k.has("thm"): return self.theorem(k)
        if t == "div" and k.has("proof"): return self.proof(k)
        if t == "div" and k.has("rem"): return self.remark(k)
        if t == "ol" and k.has("refs"): return self.refs(k)
        if t == "ol": return self.marked(k)
        if t == "figure": return self.figure(k)
        if t == "pre": return self.listing(k)
        raise ValueError("block <%s class=%r>" % (t, k.attrs.get("class")))

    def heading(self, k):
        no, rest = self.split(k, "no")
        title = self.inline(rest).strip()
        if no:
            self.count("section", no[0].text().rstrip("."))
            return [("env", r"\section{%s}" % title)]
        m = re.match(r"Appendix ([A-Z])\. (.*)$", title)
        if m:
            self.n["appendix"] += 1
            assert m[1] == chr(64 + self.n["appendix"]), title
            # A later appendix starts a page: after the full-page tables of Appendix A only the
            # heading and the top rule of the listing would fit on the page before.
            first = r"\appendix" + "\n\n" if self.n["appendix"] == 1 else r"\clearpage" + "\n\n"
            return [("env", first + r"\section{%s}" % m[2])]
        assert title == "References", title                # thebibliography prints this heading
        return []

    def equation(self, k):
        body, no = k.nodes()
        assert body.has("eqbody") and no.has("eqno")
        self.count("equation", no.text().strip("()"))
        (kind, s), = self.blocks(body.kids)
        assert kind == "display"
        return [("display", r"\begin{equation}" + "\n" + s[2:-2].strip() + "\n" + r"\end{equation}")]

    def opening(self, k, *classes):
        """Head spans of an environment, and its content as blocks."""
        first = k.nodes()[0]
        assert first.tag == "p", first.tag
        heads, rest = self.split(first, *classes)
        after = k.kids[[i for i, x in enumerate(k.kids) if x is first][0] + 1:]
        def body():
            s = self.par(rest)
            return ([("par", s)] if s else []) + self.blocks(after)
        return heads, body

    @staticmethod
    def note(span):
        return "[%s]" % tex_text(re.match(r"\((.*)\)\.$", span.text().strip())[1], False)

    def theorem(self, k):
        heads, body = self.opening(k, "head", "note")
        m = re.match(r"(Definition|Theorem|Lemma|Corollary) (\d+)\.?$", heads[0].text().strip())
        env = m[1].lower()
        self.count("lemma" if env == "corollary" else env, m[2])
        opt = self.note(heads[1]) if len(heads) > 1 else ""
        text = self.join(body())
        if text.startswith(r"\begin{marked}"): text = r"\leavevmode" + "\n" + text
        return [("env", "\\begin{%s}%s\n\\unbroken\n%s\n\\end{%s}" % (env, opt, text, env))]

    def proof(self, k):
        heads, body = self.opening(k, "head")
        label = heads[0].text().strip()
        opt = "" if label == "Proof." else "[%s]" % tex_text(label.rstrip("."), False)
        self.in_proof = True; bl = body(); self.in_proof = False
        assert bl[-1][0] in ("par", "parni"), "a proof must end with text, for the end mark"
        return [("env", "\\begin{proof}%s\n%s\n\\end{proof}" % (opt, self.join(bl)))]

    def remark(self, k):
        heads, body = self.opening(k, "head")
        label = heads[0].text().strip()
        if label == "Example.":
            env, opt = "example", ""
        else:
            self.count("remark", re.match(r"Remark (\d+)$", label)[1])
            env, opt = "remark", self.note(heads[1])
        keep = "\\unbroken\n" if env == "example" else ""     # the example is short; remarks may break
        return [("env", "\\begin{%s}%s\n%s%s\n\\end{%s}" % (env, opt, keep, self.join(body()), env))]

    def marked(self, k):
        items = []
        for li in k.nodes():
            (mark,), rest = self.split(li, "mark")
            items.append((mark.text().strip(), self.par(rest)))
        widest = max((a for a, _ in items), key=len)
        return [("env", "\\begin{marked}{%s}\n%s\n\\end{marked}"
                 % (widest, "\n".join("\\item[%s] %s" % it for it in items)))]

    def refs(self, k):
        self.cite = False; items = []
        for li in k.nodes():
            m = re.match(r"\[(\d+)\] (.*)$", self.inline(li.kids).strip(), re.S)
            items.append("\\bibitem{ref%s}\n%s" % (m[1], wrap(m[2])))
        self.cite = True
        return [("env", "\\begin{thebibliography}{9}\n\n" + "\n\n".join(items) + "\n\n\\end{thebibliography}")]

    def figure(self, k):
        cap, = k.find("figcaption")
        (lab,), rest = self.split(cap, "lab")
        kind, num = re.match(r"(Figure|Table) (\d+)\.$", lab.text().strip()).groups()
        self.count(kind.lower(), num)
        caption = self.par(rest)
        if kind == "Figure":
            pic, = k.find("tikz")
            return [("env", "\\begin{figure}[htbp]\n\\centering\n%s\n\\caption{%s}\n\\end{figure}"
                     % (self.figures[pic.attrs["name"]], caption))]
        tab, = k.find("table")
        where = "H" if self.n["appendix"] else "htbp"       # in the appendix a table stays in its place
        size = r"\footnotesize" if tab.attrs["class"] in ("path", "terms") else r"\small"
        # With [H] the class sets the caption as it does for a figure, with the space above it
        # and none below. Put the space back where a table has it.
        pre, post = (r"\setlength{\abovecaptionskip}{0pt}" + "\n", "\n" + r"\vspace{\belowcaptionskip}") if where == "H" else ("", "")
        return [("env", "\\begin{table}[%s]\n%s\\caption{%s}%s\n\\centering%s\n%s\n\\end{table}"
                 % (where, pre, caption, post, size, self.tabular(tab)))]

    def tabular(self, t):
        cls = t.attrs["class"]
        head = t.find("thead")[0].find("th")
        ncol = sum(int(h.attrs.get("colspan", 1)) for h in head)
        spec = {"path": r"@{}ll>{\raggedright\arraybackslash}p{0.42\textwidth}@{}",
                "reg": "@{}" + "l" * ncol + "@{}",
                "terms": "@{}" + "l" * ncol + "@{}",
                "prefix": r"@{}r@{\hspace{1.4em}}" + "l" * (ncol - 1) + "@{}",
                "map": r"@{}l>{\raggedright\arraybackslash}p{0.72\textwidth}@{}"}[cls]
        cells = []
        for h in head:
            s = self.inline(h.kids).strip()
            if not (s.startswith(r"\(") and s.endswith(r"\)")): s = r"\textit{%s}" % s
            n = int(h.attrs.get("colspan", 1))
            cells.append(r"\multicolumn{%d}{l}{%s}" % (n, s) if n > 1 else s)
        out = [r"\setlength{\tabcolsep}{4.5pt}" if cls == "prefix" else "", r"\begin{tabular}{%s}" % spec,
               r"\toprule", " & ".join(cells) + r" \\", r"\midrule"]
        for tr in t.find("tbody")[0].find("tr"):
            if tr.has("gap"): out.append(r"\addlinespace"); continue
            tds = tr.find("td")
            assert len(tds) == ncol, (cls, len(tds))
            out.append(" & ".join(self.inline(td.kids).strip() for td in tds) + r" \\")
        out += [r"\bottomrule", r"\end{tabular}"]
        return "\n".join(x for x in out if x)

    def listing(self, k):
        body = k.text().strip("\n")
        assert r"\end{Verbatim}" not in body
        opts = r"fontfamily=leanmono, fontsize=\fontsize{%.1fpt}{%.1fpt}\selectfont, frame=lines, framesep=6pt" \
               % (self.listing_pt, 1.3 * self.listing_pt)
        return [("env", "\\begin{Verbatim}[%s]\n%s\n\\end{Verbatim}" % (opts, body))]


def convert(page, figures, listing_pt):
    """The LaTeX source for a filled template page. `figures` maps tikz names to TikZ pictures."""
    tree = _Tree(); tree.feed(page); tree.close()
    article, = tree.root.find("article")
    c = Conv(figures, listing_pt)
    body = c.join(c.blocks(article.kids))
    out = PREAMBLE
    for key, val in (("TITLE", c.meta["title"]), ("AUTHOR", c.meta["author"]), ("DATE", c.meta["date"]),
                     ("ABSTRACT", c.meta["abstract"]), ("BODY", body)):
        assert out.count("@@%s@@" % key) == 1
        out = out.replace("@@%s@@" % key, val)
    return out, dict(c.n)
